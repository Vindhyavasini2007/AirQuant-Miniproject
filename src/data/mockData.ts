export function getCategoryForAQI(aqi: number): CPCBStandard {
  if (aqi <= 50) return CPCB_CATEGORIES['Good'];
  if (aqi <= 100) return CPCB_CATEGORIES['Satisfactory'];
  if (aqi <= 200) return CPCB_CATEGORIES['Moderate'];
  if (aqi <= 300) return CPCB_CATEGORIES['Poor'];
  if (aqi <= 400) return CPCB_CATEGORIES['Very Poor'];
  return CPCB_CATEGORIES['Severe'];
}

// Generate realistic 24-hour hourly trend relative to current base AQI
function generateHourlyTrends(baseAqi: number, basePm25: number, basePm10: number) {
  const hours = [
    '00:00', '02:00', '04:00', '06:00', '08:00', '10:00', 
    '12:00', '14:00', '16:00', '18:00', '20:00', '22:00'
  ];
  
  // Typical diurnal pattern: high early morning, lower in warm afternoon, rises in evening
  const variationFactors = [0.92, 0.96, 1.05, 1.14, 1.18, 1.08, 0.88, 0.82, 0.85, 1.02, 1.12, 1.06];

  return hours.map((hour, idx) => {
    const factor = variationFactors[idx];
    return {
      time: hour,
      aqi: Math.round(baseAqi * factor),
      pm25: Math.round(basePm25 * factor),
      pm10: Math.round(basePm10 * factor),
      temperature: Math.round(24 + 6 * Math.sin((idx - 3) * 0.5)),
    };
  });
}

// Generate 7-day past history
function generateWeeklyTrends(baseAqi: number, basePm25: number, basePm10: number) {
  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  const factors = [1.08, 1.02, 0.95, 0.98, 1.04, 0.91, 1.00];

  return days.map((day, idx) => {
    const aqi = Math.round(baseAqi * factors[idx]);
    return {
      date: `Nov ${7 + idx}`,
      dayName: day,
      aqi,
      pm25: Math.round(basePm25 * factors[idx]),
      pm10: Math.round(basePm10 * factors[idx]),
      no2: Math.round(34 + idx * 2),
      so2: 12,
      category: getCategoryForAQI(aqi).category,
    };
  });
}

// Generate 30-day past history
function generateMonthlyTrends(baseAqi: number, basePm25: number, basePm10: number) {
  const result = [];
  for (let i = 30; i >= 1; i--) {
    const variance = 1 + Math.sin(i * 0.4) * 0.22 + ((i % 5) - 2) * 0.03;
    const aqi = Math.round(baseAqi * variance);
    result.push({
      date: `Oct ${31 - (i > 15 ? i - 15 : 0)}`,
      dayName: `Day ${31 - i}`,
      aqi,
      pm25: Math.round(basePm25 * variance),
      pm10: Math.round(basePm10 * variance),
      no2: Math.round(30 + Math.cos(i) * 8),
      so2: 11,
      category: getCategoryForAQI(aqi).category,
    });
  }
  return result;
}

